import yfinance as yf

# 1. Definición de activos (3 pares: Acción vs. ETF)
tickers = ["NVDA", "QQQ", "NU", "EEM", "MSTR", "IBIT"]

print("Iniciando descarga de datos históricos (últimos 3 años)...")

# 2. Descarga desde Yahoo Finance

datos_crudos = yf.download(tickers, period="3y", auto_adjust=True)["Close"]

# 3. Auditoría de calidad y valores faltantes (NaN)
print("\n--- CALIDAD DE DATOS CRUDOS ---")
print(f"Total de registros descargados por activo: {len(datos_crudos)}")
print("Valores nulos (NaN) por activo antes de limpiar:")
print(datos_crudos.isna().sum())

# 4. Limpieza y alineación de fechas (Inner Join implícito con dropna)
# Como IBIT comenzó a cotizar en enero de 2024, eliminamos las fechas previas
# para garantizar que todos los activos se comparen exactamente en la misma ventana.
datos_limpios = datos_crudos.dropna()

print("\n--- DATOS LIMPIOS Y ALINEADOS ---")
print(
    f"Rango de fechas efectivo: {datos_limpios.index.min().date()} hasta"
    f" {datos_limpios.index.max().date()}"
)
print(f"Total de días hábiles comparables: {len(datos_limpios)}")

print("\nPrimeras 5 filas de precios de cierre ajustados:")
print(datos_limpios.head())

print("\nÚltimas 5 filas de precios de cierre ajustados:")
print(datos_limpios.tail())

# 5. Guardar muestra en CSV para verificación rápida
datos_limpios.to_csv("datos_historicos_limpios.csv")
print("\n✅ Archivo 'datos_historicos_limpios.csv' generado con éxito.")

"""#**Cálculo de Indicadores**

---


"""

# 1. Cálculo de retornos logarítmicos diarios
retornos_log = np.log(datos_limpios / datos_limpios.shift(1)).dropna()

# 2. Parámetros anuales (252 días de trading al año)
dias_anuales = 252
tasa_libre_riesgo = 0.042  # ~4.2% anual (referencia Bonos del Tesoro EE.UU.)

# 3. Construcción de la tabla de métricas cuantitativas
metricas = pd.DataFrame(index=datos_limpios.columns)

# Rentabilidad total acumulada en el período (%)
metricas["Retorno Acumulado (%)"] = (
    (datos_limpios.iloc[-1] / datos_limpios.iloc[0]) - 1
) * 100

# Retorno anualizado (%)
metricas["Retorno Anualizado (%)"] = retornos_log.mean() * dias_anuales * 100

# Volatilidad anualizada (%)
metricas["Volatilidad Anualizada (%)"] = (
    retornos_log.std() * np.sqrt(dias_anuales) * 100
)

# Ratio de Sharpe
metricas["Ratio de Sharpe"] = (
    (retornos_log.mean() * dias_anuales) - tasa_libre_riesgo
) / (retornos_log.std() * np.sqrt(dias_anuales))

# VaR Histórico Diario al 95% de confianza (%)
metricas["VaR Diario 95% (%)"] = np.percentile(retornos_log, 5, axis=0) * 100

# Drawdown Máximo (%)
riqueza_acumulada = (1 + retornos_log).cumprod()
picos_previos = riqueza_acumulada.cummax()
drawdowns = (riqueza_acumulada - picos_previos) / picos_previos
metricas["Max Drawdown (%)"] = drawdowns.min() * 100

print("--- TABLA COMPARATIVA DE RIESGO Y RETORNO (2024 - 2026) ---")
print(metricas.round(2))

"""El ganador absoluto en eficiencia riesgo-retorno: **NVDA** logró un Ratio de Sharpe de 0.83 (retorno anualizado de 43.71% con volatilidad de 47.74%), superando con creces a su ETF de referencia QQQ (Sharpe 0.62, retorno anualizado de 17.30% y volatilidad de 21.24%)."""

