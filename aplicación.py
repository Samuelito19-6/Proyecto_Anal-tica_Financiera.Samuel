st.dataframe(
    metricas.style.format("{:.2f}").background_gradient(
        subset=["Ratio de Sharpe"], cmap="RdYlGn"
    ),
    use_container_width=True,
)

# --- SECCIÓN 2: GRÁFICOS PRINCIPALES ---
